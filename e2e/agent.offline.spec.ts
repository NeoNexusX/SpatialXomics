import { test, expect, openAgent, fulfillSse, sseText, sseTool, MODEL, API_KEY, PNG } from './fixtures/offline.js'

test.describe('Agent connection', () => {
  test.use({ connectionModel: '' })

  test('probes models, excludes unsupported ones, and persists the selected connection', async ({ page }) => {
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await expect(panel.getByRole('heading', { name: 'Connection' })).toBeVisible()
    await expect(panel.getByLabel('API key', { exact: true })).toHaveAttribute('type', 'password')
    await panel.getByRole('button', { name: 'Show key' }).click()
    await expect(panel.getByLabel('API key', { exact: true })).toHaveValue(API_KEY)
    await expect(panel.locator('button[type="submit"]')).toBeDisabled()

    await panel.getByRole('button', { name: 'Fetch models' }).click()
    await expect(panel.getByRole('radio', { name: MODEL })).toBeChecked()
    await expect(panel.getByText('1 available · tested 3/3', { exact: false })).toBeVisible()
    await expect(panel.getByRole('radio')).toHaveCount(1)
    await panel.locator('button[type="submit"]').click()
    await expect(panel.getByPlaceholder('Message SXO Harness Agent')).toBeVisible()

    await page.reload()
    const restored = await openAgent(page)
    await expect(restored.getByPlaceholder('Message SXO Harness Agent')).toBeVisible()
    await restored.getByRole('button', { name: 'Connection', exact: true }).click()
    await expect(restored.getByRole('radio', { name: MODEL })).toBeChecked()
    await restored.getByRole('button', { name: 'Clear', exact: true }).click()
    await expect(restored.getByRole('button', { name: 'Click again to confirm' })).toBeVisible()
    await expect(restored.getByLabel('API key', { exact: true })).toHaveValue(API_KEY)
    await restored.getByRole('button', { name: 'Click again to confirm' }).click()
    await expect(restored.getByLabel('API key', { exact: true })).toHaveValue('')
    await expect(restored.locator('button[type="submit"]')).toBeDisabled()
    expect(await page.evaluate(() => localStorage.getItem('assistant_connection'))).toBeNull()
  })
})

test.describe('Agent browser journeys', () => {
  test('keeps drafts across settings and sends multiline input exactly once', async ({ page, backend }) => {
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    const input = panel.getByPlaceholder('Message SXO Harness Agent')
    await expect(panel.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
    await input.fill('Summarize the data')
    await input.press('Shift+Enter')
    await input.pressSequentially('Include metadata')
    await expect(input).toHaveValue('Summarize the data\nInclude metadata')
    const draft = await input.inputValue()
    await panel.getByRole('button', { name: 'Connection', exact: true }).click()
    await panel.getByRole('button', { name: 'Back', exact: true }).click()
    await expect(input).toHaveValue(draft)
    await input.press('Enter')
    await expect(panel.getByText('E2E answer ready.', { exact: true })).toBeVisible()
    await expect(input).toHaveValue('')
    expect(backend.requests).toHaveLength(1)
    expect(backend.requests[0]!.messages.at(-1)!.content).toContainEqual({ type: 'text', text: draft.trim() })
  })

  test('executes a real registered tool and passes its result back to the model', async ({ page, backend }) => {
    backend.reply = (route) => fulfillSse(route, backend.requests.length === 1
      ? sseTool('get_page_state') : sseText('Page state inspected.'))
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Inspect the current page')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByText('Page state inspected.', { exact: true })).toBeVisible()
    expect(backend.requests).toHaveLength(2)
    expect(backend.requests[0]!.tools).toContainEqual(expect.objectContaining({ name: 'get_page_state' }))
    const results = backend.requests[1]!.messages.flatMap((m) => m.content).filter((part) => part.type === 'tool_result')
    expect(results).toHaveLength(1)
    expect(results[0]).toMatchObject({ tool_use_id: 'e2e-tool-call' })
    expect(results[0]!.is_error).not.toBe(true)
    expect(JSON.stringify(results[0]!.content)).toContain('mean spectrum: not loaded')
  })

  test('reports a permanent endpoint error and regenerates without duplicating the question', async ({ page, backend }) => {
    backend.reply = (route) => route.fulfill({ status: 401, headers: { 'access-control-allow-origin': '*' }, json: {
      type: 'error', error: { type: 'authentication_error', message: 'Invalid API key' },
    } })
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Retry this question')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByRole('alert')).toContainText('Invalid key (HTTP 401)')
    expect(backend.requests).toHaveLength(1)
    backend.reply = (route) => fulfillSse(route, sseText('Recovered answer.'))
    await panel.getByRole('button', { name: 'Retry', exact: true }).click()
    await expect(panel.getByText('Recovered answer.', { exact: true })).toBeVisible()
    await expect(panel.getByRole('log').getByText('Retry this question', { exact: true })).toHaveCount(1)
    await expect(panel.getByText('Invalid key (HTTP 401)', { exact: false })).toHaveCount(0)
    expect(backend.requests).toHaveLength(2)
  })

  test('stops an outstanding request and prevents its late reply from entering a new conversation', async ({ page, backend }) => {
    let release!: () => void
    const held = new Promise<void>((resolve) => { release = resolve })
    backend.reply = async (route) => {
      await held
      await fulfillSse(route, sseText('Late cancelled answer.')).catch(() => {})
    }
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Wait for cancellation')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect.poll(() => backend.requests.length).toBe(1)
    await panel.getByRole('button', { name: 'Stop', exact: true }).click()
    await expect(panel.getByText('Stopped', { exact: true })).toBeVisible()
    await panel.getByRole('button', { name: 'New chat', exact: true }).click()
    release()
    backend.reply = (route) => fulfillSse(route, sseText('New conversation answer.'))
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Start fresh')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByText('New conversation answer.', { exact: true })).toBeVisible()
    await expect(panel.getByText('Late cancelled answer.', { exact: true })).toHaveCount(0)
    expect(JSON.stringify(backend.requests[1]!.messages)).not.toContain('Wait for cancellation')
  })

  test('restores OPFS messages and makes the same conversation read-only in a second tab', async ({ page, context }) => {
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Remember this conversation')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByText('E2E answer ready.', { exact: true })).toBeVisible()
    await expect(panel.getByRole('button', { name: 'New chat', exact: true })).toBeEnabled()
    // Closing the document releases the write lease; reopening must replay the durable log.
    await page.goto('about:blank')
    await page.goto('/vizworkbench')
    const restored = await openAgent(page)
    await expect(restored.getByRole('log').getByText('Remember this conversation', { exact: true })).toBeVisible()
    await expect(restored.getByRole('log').getByText('E2E answer ready.', { exact: true })).toBeVisible()

    const other = await context.newPage()
    await other.goto('/vizworkbench')
    const readOnly = await openAgent(other)
    await expect(readOnly.getByText('This conversation is open in another tab and is read-only here.')).toBeVisible()
    await expect(readOnly.getByRole('log').getByText('E2E answer ready.', { exact: true })).toBeVisible()
    await readOnly.getByPlaceholder('Message SXO Harness Agent').fill('Must not send')
    await expect(readOnly.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
    await other.close()
  })

  test('sends image attachments through the adapter and restores their OPFS artifacts', async ({ page, backend }) => {
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    const chooser = page.waitForEvent('filechooser')
    await panel.getByRole('button', { name: 'Add images' }).click()
    await (await chooser).setFiles({ name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from(PNG, 'base64') })
    await expect(panel.getByRole('button', { name: 'Remove image' })).toBeVisible()
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Describe this image')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByText('E2E answer ready.', { exact: true })).toBeVisible()
    await expect.poll(() => backend.requests.length).toBe(1)
    await expect(panel.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
    expect(backend.requests[0]!.messages.at(-1)!.content).toContainEqual(expect.objectContaining({ type: 'image' }))
    await expect(panel.getByRole('button', { name: 'Remove image' })).toHaveCount(0)
    await page.goto('about:blank')
    await page.goto('/vizworkbench')
    const restored = await openAgent(page)
    const image = restored.getByRole('img', { name: 'Image', exact: true })
    await expect(image).toBeVisible()
    await expect.poll(() => image.evaluate((img) => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  })
})

test.describe('Agent storage fallback', () => {
  test.use({ temporaryStorage: true })

  test('continues chatting when OPFS is unavailable and explains that reload clears history', async ({ page }) => {
    await page.goto('/vizworkbench')
    const panel = await openAgent(page)
    await expect(panel.getByText('Temporary conversation. Reloading clears it.')).toBeVisible()
    await panel.getByPlaceholder('Message SXO Harness Agent').fill('Temporary question')
    await panel.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(panel.getByText('E2E answer ready.', { exact: true })).toBeVisible()
    await expect(panel.getByRole('button', { name: 'Stop', exact: true })).toHaveCount(0)
    await page.reload()
    const restored = await openAgent(page)
    await expect(restored.getByText('Temporary conversation. Reloading clears it.')).toBeVisible()
    await expect(restored.getByText('Temporary question', { exact: true })).toHaveCount(0)
  })
})
